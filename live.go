// Action represents the type of change in a live query notification.
type Action int

const (
	ActionCreate        Action = C.SR_ACTION_CREATE
	ActionUpdate        Action = C.SR_ACTION_UPDATE
	ActionDelete        Action = C.SR_ACTION_DELETE
	ActionUnimplemented Action = C.SR_ACTION_UNIMPLEMENTED
)

func (a Action) String() string {
	switch a {
	case ActionCreate:
		return "CREATE"
	case ActionUpdate:
		return "UPDATE"
	case ActionDelete:
		return "DELETE"
	default:
		return "UNIMPLEMENTED"
	}
}

// Notification is a live query event received from the database.
type Notification struct {
	QueryID string
	Action  Action
	Data    Value
}

// LiveQuery is a handle to an active live query session.
// Read notifications from Ch. Call db.Kill to stop.
//
// Note: the underlying C API (sr_select_live) does not return the server-side
// live query UUID. That UUID only appears inside each Notification.QueryID.
// The ID field here is a client-side session identifier generated by the
// library for use with db.Kill.
type LiveQuery struct {
	// ID is the session identifier assigned by the library.
	ID string
	// Ch receives notifications as they arrive.
	// The channel is closed when the stream ends.
	Ch <-chan Notification

	stream     *C.sr_stream_t
	resource   string
	done       chan struct{}
	stopping   atomic.Bool
	srvQueryID atomic.Value // string — server-side query UUID, set from first notification
}

// uuidToString formats 16 raw UUID bytes as a standard UUID string.
func uuidToString(b [16]C.uint8_t) string {
	var raw [16]byte
	for i := range raw {
		raw[i] = byte(b[i])
	}
	h := hex.EncodeToString(raw[:])
	return fmt.Sprintf("%s-%s-%s-%s-%s", h[0:8], h[8:12], h[12:16], h[16:20], h[20:32])
}

func extractNotification(cn *C.sr_notification_t) Notification {
	return Notification{
		QueryID: uuidToString(cn.query_id._0),
		Action:  Action(cn.action),
		Data:    extractValue(&cn.data),
	}
}

func generateID() string {
	var b [16]byte
	rand.Read(b[:])
	h := hex.EncodeToString(b[:])
	return fmt.Sprintf("%s-%s-%s-%s-%s", h[0:8], h[8:12], h[12:16], h[16:20], h[20:32])
}

// liveQueryMap is the DB-level registry of active live query sessions.
type liveQueryMap struct {
	mu       sync.Mutex
	sessions map[string]*LiveQuery
}

func newLiveQueryMap() *liveQueryMap {
	return &liveQueryMap{sessions: make(map[string]*LiveQuery)}
}

func (m *liveQueryMap) add(lq *LiveQuery) {
	m.mu.Lock()
	m.sessions[lq.ID] = lq
	m.mu.Unlock()
}

func (m *liveQueryMap) remove(id string) (*LiveQuery, bool) {
	m.mu.Lock()
	lq, ok := m.sessions[id]
	if ok {
		delete(m.sessions, id)
	}
	m.mu.Unlock()
	return lq, ok
}

// closeAll kills all active live query sessions. Must be called before
// sr_surreal_disconnect so the stream pointers are still valid.
func (m *liveQueryMap) closeAll(db *DB) {
	m.mu.Lock()
	sessions := make([]*LiveQuery, 0, len(m.sessions))
	for _, lq := range m.sessions {
		sessions = append(sessions, lq)
	}
	m.sessions = make(map[string]*LiveQuery)
	m.mu.Unlock()

	// Set stop flag and send poison pills to unblock sr_stream_next.
	for _, lq := range sessions {
		lq.stopping.Store(true)
		sendPoisonPill(db, lq)
	}
	// Wait for all goroutines to exit (they call sr_stream_kill in defer).
	for _, lq := range sessions {
		<-lq.done
	}
	// No poison cleanup needed — DB is about to disconnect.
}

// poisonRecordID returns a unique SurrealQL record identifier used as a
// poison pill to unblock sr_stream_next when stopping a live query.
func poisonRecordID(lq *LiveQuery) string {
	return fmt.Sprintf("%s:__lq_%s", lq.resource, strings.ReplaceAll(lq.ID, "-", ""))
}

// sendPoisonPill inserts a dummy record into the watched table, which
// triggers a notification on the live query stream and unblocks sr_stream_next.
func sendPoisonPill(db *DB, lq *LiveQuery) {
	rid := poisonRecordID(lq)
	db.query(fmt.Sprintf("CREATE %s SET __lq = true", rid), nil)
}

// cleanupPoisonPill removes the dummy record inserted by sendPoisonPill.
func cleanupPoisonPill(db *DB, lq *LiveQuery) {
	rid := poisonRecordID(lq)
	db.query(fmt.Sprintf("DELETE %s", rid), nil)
}

// killServerSide terminates the server-side live query subscription.
func killServerSide(db *DB, lq *LiveQuery) {
	if v := lq.srvQueryID.Load(); v != nil {
		id := v.(string)
		cID := cstring(id)
		defer freeCString(cID)
		var errPtr C.sr_string_t
		C.sr_kill(db.c, &errPtr, cID)
		// Ignore error — best effort.
		if errPtr != nil {
			C.sr_free_string(errPtr)
		}
	}
}

// Live creates a live query on the given resource (table name) and returns
// a LiveQuery whose Ch channel receives notifications as they arrive.
//
// The context controls the timeout for the sr_select_live C call. If ctx is
// cancelled after the call starts but before it completes, the goroutine
// finishes in the background and the stream is killed.
//
// Use lq.ID to identify the session, and db.Kill(lq) to stop it.
func (db *DB) Live(ctx context.Context, resource string) (*LiveQuery, error) {
	return runWithSem(ctx, db.sem, func() (*LiveQuery, error) {
		cRes := cstring(resource)
		defer freeCString(cRes)

		var errPtr C.sr_string_t
		var streamPtr *C.sr_stream_t
		rc := C.sr_select_live(db.c, &errPtr, &streamPtr, cRes)
		if err := surrealError(rc, errPtr); err != nil {
			return nil, err
		}

		ch := make(chan Notification, 64)
		done := make(chan struct{})
		lq := &LiveQuery{
			ID:       generateID(),
			Ch:       ch,
			stream:   streamPtr,
			resource: resource,
			done:     done,
		}

		db.live.add(lq)

		go func() {
			defer close(done)
			defer close(ch)
			// The goroutine owns the stream: it is the only caller of
			// sr_stream_next, and it frees the stream when done.
			defer C.sr_stream_kill(streamPtr)

			for {
				var cn C.sr_notification_t
				rc := C.sr_stream_next(streamPtr, &cn)
				if rc <= 0 {
					return
				}
				if lq.stopping.Load() {
					return
				}
				n := extractNotification(&cn)
				lq.srvQueryID.CompareAndSwap(nil, n.QueryID)
				ch <- n
			}
		}()

		return lq, nil
	}, func(lq *LiveQuery) {
		// Cleanup on context cancellation: stop and kill the stream.
		lq.stopping.Store(true)
		sendPoisonPill(db, lq)
		go func() {
			<-lq.done
			killServerSide(db, lq)
			cleanupPoisonPill(db, lq)
			db.live.remove(lq.ID)
		}()
	})
}

// Kill stops a live query session and frees its resources.
func (db *DB) Kill(lq *LiveQuery) {
	if lq, ok := db.live.remove(lq.ID); ok {
		lq.stopping.Store(true)
		sendPoisonPill(db, lq)
		<-lq.done
		killServerSide(db, lq)
		cleanupPoisonPill(db, lq)
	}
}
